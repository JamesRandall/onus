#!/usr/bin/env bash
# Renders the Homebrew formula for a release (docs/CHANGES.md item 182) from
# the version and a directory holding the release archives:
#   scripts/brew-formula.sh <version> <archives-dir>
# The release workflow runs it after publishing and pushes the result to the
# tap, JamesRandall/homebrew-onus, as Formula/compiler.rb, so that
# `brew install JamesRandall/onus/compiler` installs `onus`.
set -euo pipefail
version=$1
dir=$2
base=https://github.com/JamesRandall/onus/releases/download/v$version
sum() {
  if command -v sha256sum > /dev/null 2>&1; then sha256sum "$1" | cut -d' ' -f1; else shasum -a 256 "$1" | cut -d' ' -f1; fi
}
mac_arm=$(sum "$dir/onus-$version-macos-arm64.tar.gz")
linux_x86=$(sum "$dir/onus-$version-linux-x86_64.tar.gz")
linux_arm=$(sum "$dir/onus-$version-linux-arm64.tar.gz")
cat <<FORMULA
# Generated by scripts/brew-formula.sh in JamesRandall/onus for each release. Do not edit.
class Compiler < Formula
  desc "Onus compiler: a model writes bodies, a human reviews contracts, the compiler checks"
  homepage "https://github.com/JamesRandall/onus"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/onus-$version-macos-arm64.tar.gz"
      sha256 "$mac_arm"
    end
  end

  on_linux do
    on_intel do
      url "$base/onus-$version-linux-x86_64.tar.gz"
      sha256 "$linux_x86"
    end
    on_arm do
      url "$base/onus-$version-linux-arm64.tar.gz"
      sha256 "$linux_arm"
    end
  end

  # Proofs; without it every obligation is checked at run time. Native output needs clang, which macOS provides.
  depends_on "z3"

  def install
    bin.install "onus"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/onus --version")
    (testpath/"hello.onus").write <<~ONUS
      module hello

      fn twice(n: Int) -> Int
        ensures result == 2 * n
      {
        return n * 2
      }

      example doubles {
        twice(n: 21) == 42
      }
    ONUS
    system bin/"onus", "check", "hello.onus"
  end
end
FORMULA
