#!/usr/bin/env node
// Generates self/bundle.onus (docs/CHANGES.md item 180): the standard
// library's sources, the JavaScript runtime and the C runtime as text
// constants, so that the compiler built from self/ carries them and needs
// no repository, --stdlib or --runtime. The version is the root package's.
//   node scripts/bundle.mjs [out-path]      (default self/bundle.onus)
// The result is formatted with the TypeScript compiler's `onus fmt`, so
// packages/compiler must be built. A test regenerates it and compares.
import { readdirSync, readFileSync, statSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = process.argv[2] ?? join(root, 'self', 'bundle.onus');

/** Every file under `dir` (recursively) accepted by `keep`, as [relative path, text], sorted. */
function files(dir, keep) {
  const found = [];
  const visit = (d) => {
    for (const f of readdirSync(d).sort()) {
      const p = join(d, f);
      if (statSync(p).isDirectory()) visit(p);
      else if (keep(f)) found.push([relative(dir, p).split('\\').join('/'), readFileSync(p, 'utf8')]);
    }
  };
  visit(dir);
  return found;
}

/** An Onus text literal: the escapes the lexer accepts (\n \t \r \0 \\ \"), everything else raw. */
function literal(text) {
  let s = '"';
  for (const ch of text) {
    const c = ch.codePointAt(0);
    if (ch === '"') s += '\\"';
    else if (ch === '\\') s += '\\\\';
    else if (ch === '\n') s += '\\n';
    else if (ch === '\t') s += '\\t';
    else if (ch === '\r') s += '\\r';
    else if (c === 0) s += '\\0';
    else if (c < 0x20 || c === 0x7f) throw new Error(`control character U+${c.toString(16)} in a bundled file`);
    else s += ch;
  }
  return s + '"';
}

const entries = [
  ...files(join(root, 'packages', 'stdlib', 'std'), (f) => f.endsWith('.onus')).map(([p, t]) => [`std/${p}`, t]),
  ...files(join(root, 'packages', 'runtime', 'dist'), (f) => f.endsWith('.js')).map(([p, t]) => [`runtime/${p}`, t]),
  ...files(join(root, 'packages', 'runtime', 'native'), (f) => f.endsWith('.c') || f.endsWith('.h') || f.startsWith('LICENSE')).map(([p, t]) => [`native/${p}`, t]),
];
const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;

const lines = [
  'module bundle',
  '',
  '-- Generated by scripts/bundle.mjs from packages/stdlib/std, packages/runtime/dist',
  '-- and packages/runtime/native (docs/CHANGES.md item 180). Do not edit: the',
  '-- standard library, the JavaScript runtime and the C runtime the compiler',
  '-- carries, so that `onus` needs no repository, `--stdlib` or `--runtime`.',
  'pub record Entry {',
  '  path: Text',
  '  text: Text',
  '}',
  '',
  `pub const version: Text = ${literal(version)}`,
  '',
  'pub const files: List[Entry] = [',
  ...entries.map(([p, t], i) => `  Entry { path: ${literal(p)}, text: ${literal(t)} }${i < entries.length - 1 ? ',' : ''}`),
  ']',
  '',
  '-- The bundled file at `path`, or None.',
  'pub fn find(path: Text) -> Option[Text] {',
  '  for e: Entry in files {',
  '    if e.path == path {',
  '      return Some(value: e.text)',
  '    }',
  '  }',
  '  return None',
  '}',
  '',
  '-- The bundled files whose paths start with `prefix`, in bundle order.',
  'pub fn under(prefix: Text) -> List[Entry] may alloc, mutate {',
  '  var out: Builder[Entry] = List.builder()',
  '  for e: Entry in files {',
  '    if Text.starts_with(t: e.path, prefix: prefix) {',
  '      List.push(b: inout out, x: e)',
  '    }',
  '  }',
  '  return List.finish(b: out)',
  '}',
  '',
];
const tmp = mkdtempSync(join(tmpdir(), 'onus-bundle-'));
const draft = join(tmp, 'bundle.onus');
writeFileSync(draft, lines.join('\n'));
const fmt = spawnSync(process.execPath, [join(root, 'packages', 'compiler', 'dist', 'cli', 'main.js'), 'fmt', draft], { encoding: 'utf8' });
if (fmt.status !== 0) {
  process.stderr.write(`bundle: onus fmt failed:\n${fmt.stdout}${fmt.stderr}`);
  process.exit(1);
}
writeFileSync(out, readFileSync(draft, 'utf8'));
rmSync(tmp, { recursive: true, force: true });
process.stdout.write(`bundle: wrote ${out} (${entries.length} files, version ${version})\n`);
